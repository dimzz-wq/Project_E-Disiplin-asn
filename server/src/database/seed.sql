-- Trigger pembantu untuk kolom updated_at
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. Organizational Units
CREATE TABLE IF NOT EXISTS org_units (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  head_name VARCHAR(150),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. Users (System users who can log in)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nip VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'pegawai'
    CHECK (role IN ('admin', 'atasan', 'pemeriksa', 'bkpsdm', 'pegawai', 'inspektorat')),
  unit_id INT,
  position VARCHAR(150),
  avatar VARCHAR(255),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (unit_id) REFERENCES org_units(id) ON DELETE SET NULL
);

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 3. Employees (Master data of all ASN)
CREATE TABLE IF NOT EXISTS employees (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nip VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  unit_id INT,
  position VARCHAR(150),
  phone VARCHAR(20),
  email VARCHAR(150),
  avatar VARCHAR(255),
  status VARCHAR(20) DEFAULT 'active'
    CHECK (status IN ('active', 'inactive', 'suspended', 'pensiun')),
  type VARCHAR(10) DEFAULT 'PNS'
    CHECK (type IN ('PNS', 'PPPK', 'Honorer')),
  rank_grade VARCHAR(50),
  join_date DATE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (unit_id) REFERENCES org_units(id) ON DELETE SET NULL
);

DROP TRIGGER IF EXISTS trg_employees_updated_at ON employees;
CREATE TRIGGER trg_employees_updated_at BEFORE UPDATE ON employees
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 4. Attendance Records
CREATE TABLE IF NOT EXISTS attendance (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INT NOT NULL,
  date DATE NOT NULL,
  time_in TIME,
  time_out TIME,
  status VARCHAR(20) NOT NULL DEFAULT 'hadir'
    CHECK (status IN ('hadir', 'terlambat', 'alpa', 'ijin', 'sakit', 'cuti', 'dinas_luar')),
  late_minutes INT DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE,
  CONSTRAINT uq_employee_date UNIQUE (employee_id, date)
);

-- 5. Violation Reports
CREATE TABLE IF NOT EXISTS reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_no VARCHAR(50) NOT NULL UNIQUE,
  reporter_id INT,
  reporter_name VARCHAR(150),
  reported_employee_id INT NOT NULL,
  category VARCHAR(50) NOT NULL
    CHECK (category IN ('kehadiran', 'kinerja', 'kode_etik', 'penyalahgunaan_wewenang', 'pidana', 'lainnya')),
  title VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  incident_date DATE NOT NULL,
  incident_location VARCHAR(255),
  priority VARCHAR(20) DEFAULT 'sedang'
    CHECK (priority IN ('rendah', 'sedang', 'tinggi', 'kritis')),
  status VARCHAR(30) DEFAULT 'diajukan'
    CHECK (status IN ('draft', 'diajukan', 'diverifikasi', 'ditolak', 'ditingkatkan_ke_kasus')),
  rejection_reason TEXT,
  verified_by INT,
  verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (reporter_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (reported_employee_id) REFERENCES employees(id) ON DELETE CASCADE,
  FOREIGN KEY (verified_by) REFERENCES users(id) ON DELETE SET NULL
);

DROP TRIGGER IF EXISTS trg_reports_updated_at ON reports;
CREATE TRIGGER trg_reports_updated_at BEFORE UPDATE ON reports
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 6. Disciplinary Cases
CREATE TABLE IF NOT EXISTS cases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_no VARCHAR(50) NOT NULL UNIQUE,
  report_id INT,
  subject_employee_id INT NOT NULL,
  pic_id INT,
  category VARCHAR(50) NOT NULL
    CHECK (category IN ('kehadiran', 'kinerja', 'kode_etik', 'penyalahgunaan_wewenang', 'pidana', 'lainnya')),
  title VARCHAR(255) NOT NULL,
  description TEXT,
  status VARCHAR(30) DEFAULT 'baru'
    CHECK (status IN ('baru', 'penyelidikan', 'pemeriksaan', 'sidang_kode_etik', 'putusan', 'banding', 'selesai', 'dibatalkan')),
  priority VARCHAR(20) DEFAULT 'sedang'
    CHECK (priority IN ('rendah', 'sedang', 'tinggi', 'kritis')),
  level VARCHAR(20) DEFAULT 'ringan'
    CHECK (level IN ('ringan', 'sedang', 'berat')),
  recommendation TEXT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE SET NULL,
  FOREIGN KEY (subject_employee_id) REFERENCES employees(id) ON DELETE CASCADE,
  FOREIGN KEY (pic_id) REFERENCES users(id) ON DELETE SET NULL
);

DROP TRIGGER IF EXISTS trg_cases_updated_at ON cases;
CREATE TRIGGER trg_cases_updated_at BEFORE UPDATE ON cases
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 7. Case Timeline
CREATE TABLE IF NOT EXISTS case_timeline (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id INT NOT NULL,
  action VARCHAR(255) NOT NULL,
  actor_id INT,
  notes TEXT,
  type VARCHAR(30) DEFAULT 'status_change',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 8. Examinations (BAP)
CREATE TABLE IF NOT EXISTS examinations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id INT NOT NULL,
  bap_no VARCHAR(50) NOT NULL UNIQUE,
  examiner_id INT,
  examiner_name VARCHAR(150),
  examinee_id INT NOT NULL,
  date DATE NOT NULL,
  time_start TIME,
  time_end TIME,
  location VARCHAR(255),
  notes TEXT,
  questions_answers JSONB,
  status VARCHAR(30) DEFAULT 'draft'
    CHECK (status IN ('draft', 'selesai', 'ditandatangani')),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (examiner_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (examinee_id) REFERENCES employees(id) ON DELETE CASCADE
);

DROP TRIGGER IF EXISTS trg_examinations_updated_at ON examinations;
CREATE TRIGGER trg_examinations_updated_at BEFORE UPDATE ON examinations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 9. Disciplinary Decisions (SK Hukuman)
CREATE TABLE IF NOT EXISTS decisions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id INT NOT NULL UNIQUE,
  decision_no VARCHAR(50) NOT NULL UNIQUE,
  employee_id INT NOT NULL,
  sanction_type VARCHAR(100) NOT NULL,
  sanction_level VARCHAR(20) NOT NULL
    CHECK (sanction_level IN ('ringan', 'sedang', 'berat')),
  effective_date DATE NOT NULL,
  end_date DATE,
  legal_basis TEXT,
  decision_signer VARCHAR(150),
  signer_position VARCHAR(150),
  notes TEXT,
  status VARCHAR(30) DEFAULT 'berlaku'
    CHECK (status IN ('berlaku', 'banding', 'dibatalkan', 'selesai')),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE CASCADE
);

DROP TRIGGER IF EXISTS trg_decisions_updated_at ON decisions;
CREATE TRIGGER trg_decisions_updated_at BEFORE UPDATE ON decisions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 10. Documents / File Attachments
CREATE TABLE IF NOT EXISTS documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id INT,
  report_id INT,
  name VARCHAR(255) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  file_path VARCHAR(500) NOT NULL,
  file_size BIGINT,
  mime_type VARCHAR(100),
  uploader_id INT,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE CASCADE,
  FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE CASCADE,
  FOREIGN KEY (uploader_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 11. Audit Logs
CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT,
  user_name VARCHAR(150),
  action VARCHAR(100) NOT NULL,
  detail TEXT,
  module VARCHAR(50),
  ip_address VARCHAR(45),
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- 12. Refresh Tokens (JWT)
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL,
  token VARCHAR(500) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

